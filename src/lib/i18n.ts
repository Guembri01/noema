/** Translate a key for a locale, falling back to English. */
export function t(locale: string, key: keyof Dict): string {
  const dict = isLocale(locale) ? DICTS[locale] : DICTS.en;
  return dict[key] ?? en[key];
}

/** Every supported key (useful for type-ahead and coverage checks). */
export function translationKeys(): (keyof Dict)[] {
  return Object.keys(en) as (keyof Dict)[];
}

/** Keys actually present in one locale's dictionary (used by the parity test). */
export function translationKeysFor(locale: string): (keyof Dict)[] {
  const dict = isLocale(locale) ? DICTS[locale] : DICTS.en;
  return Object.keys(dict) as (keyof Dict)[];
}
