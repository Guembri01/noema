/**
 * Minimal translation layer. Keys cover the app chrome; unknown locales and
 * missing keys fall back to English. RTL is expressed via `directionOf`.
 */

export const LOCALES = [
  { code: "en", label: "English", dir: "ltr" },
  { code: "fr", label: "Français", dir: "ltr" },
  { code: "es", label: "Español", dir: "ltr" },
  { code: "de", label: "Deutsch", dir: "ltr" },
  { code: "ar", label: "العربية", dir: "rtl" },
] as const;

export type LocaleCode = (typeof LOCALES)[number]["code"];

export function isLocale(value: string): value is LocaleCode {
  return LOCALES.some((locale) => locale.code === value);
}

/** Text direction for a locale (RTL for Arabic/Hebrew/Persian). */
export function directionOf(locale: string): "ltr" | "rtl" {
  return locale === "ar" || locale === "he" || locale === "fa" ? "rtl" : "ltr";
}

